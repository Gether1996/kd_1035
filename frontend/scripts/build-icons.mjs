// Builds public/icons.svg – one SVG sprite with every icon the site uses.
// Run: npm run icons   (Lucide icons: ISC license, Simple Icons: CC0)
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const modules = new URL('../node_modules/', import.meta.url);
const lucideDir = new URL('lucide-static/icons/', modules);
const simpleDir = new URL('simple-icons/icons/', modules);

const LUCIDE = [
  'arrow-left', 'arrow-right', 'arrow-up-right', 'bell', 'bell-off', 'calendar-days', 'calendar-off', 'calendar-plus', 'camera', 'castle', 'check',
  'chevron-down', 'chevron-right', 'chevron-up', 'clock', 'copy', 'crown', 'download', 'eye', 'eye-off', 'flag', 'flame', 'gift', 'hand-helping', 'heart', 'info', 'key-round', 'languages', 'laugh', 'lightbulb',
  'link', 'log-in', 'log-out', 'map', 'menu', 'messages-square', 'pencil', 'pin', 'plus', 'repeat', 'reply', 'scale', 'search', 'send', 'shield', 'skull', 'swords', 'trash-2', 'trophy', 'users', 'x',
];
const BRANDS = ['discord', 'facebook'];

const inner = (svg) =>
  svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>')).replace(/\s*\n\s*/g, '');

const symbols = [
  ...LUCIDE.map((name) => {
    const svg = readFileSync(new URL(`${name}.svg`, lucideDir), 'utf8');
    return `<symbol id="${name}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-linecap="round" stroke-linejoin="round">${inner(svg)}</symbol>`;
  }),
  ...BRANDS.map((name) => {
    const svg = readFileSync(new URL(`${name}.svg`, simpleDir), 'utf8');
    return `<symbol id="${name}" viewBox="0 0 24 24" fill="currentColor">${inner(svg).replace(/<title>.*?<\/title>/, '')}</symbol>`;
  }),
];

const sprite = `<svg xmlns="http://www.w3.org/2000/svg"><!-- Lucide (ISC) + Simple Icons (CC0) -->${symbols.join('')}</svg>\n`;
writeFileSync(new URL('../public/icons.svg', import.meta.url), sprite);
// the sprite URL carries a hash of its content: browsers keep icons.svg for 7 days (nginx), so a new icon would be
// missing until then (Tipy a triky on phones, 11. 10. 2026)
const version = createHash('sha1').update(sprite).digest('hex').slice(0, 8);
writeFileSync(
  new URL('../src/app/shared/icons-version.ts', import.meta.url),
  `// generated by scripts/build-icons.mjs (npm run icons) – do not edit\nexport const ICONS_VERSION = '${version}';\n`,
);
console.log(`icons.svg: ${symbols.length} icons`);
